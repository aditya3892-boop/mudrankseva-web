/* ── Types ── */
export interface CalcResult {
  propValue: number;
  isFemale: boolean;
  baseRate: number;
  baseAmt: number;
  metroCessAmt: number | null;
  lbtAmt: number | null;
  totalDutyRate: number;
  totalDutyAmt: number;
  regFeeAmt: number;
  regFeeCapped: boolean;
  grandTotal: number;
}

export interface ReportInput {
  name: string;
  phone: string;
  result: CalcResult;
  district: string | null;
  areaType: "corporation" | "council" | "rural";
  gender: "male" | "female";
  surveyNo: string;
  propValue: number;
  lang: string;
}

