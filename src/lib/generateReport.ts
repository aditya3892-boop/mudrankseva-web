/* ── Devanagari font loader ──
   Place NotoSansDevanagari-Regular.ttf in public/fonts/ to enable Marathi
   PDF labels. Falls back to English labels silently if the file is absent. */
async function loadDevanagariFont(doc: jsPDF): Promise<boolean> {
  try {
    const res = await fetch("/fonts/NotoSansDevanagari-Regular.ttf");
    if (!res.ok) return false;
    const buf = await res.arrayBuffer();
    const bytes = new Uint8Array(buf);
    let binary = "";
    const chunk = 8192;
    for (let i = 0; i < bytes.length; i += chunk)
      binary += String.fromCharCode(...bytes.slice(i, Math.min(i + chunk, bytes.length)));
    const b64 = btoa(binary);
    doc.addFileToVFS("NotoSansDevanagari.ttf", b64);
    doc.addFont("NotoSansDevanagari.ttf", "NotoSansDevanagari", "normal");
    doc.addFont("NotoSansDevanagari.ttf", "NotoSansDevanagari", "bold");
    return true;
  } catch {
    return false;
  }
}

export async function generateStampDutyReport(input: ReportInput): Promise<void> {
  const { name, phone, result, district, areaType, gender, surveyNo, lang } = input;
  const isMr = lang === "mr";

  const doc = new jsPDF({ unit: "mm", format: "a4", orientation: "portrait" });
  const W   = 210;
  const M   = 16;
  const CW  = W - 2 * M;
  let y     = 0;

  /* ── Load Devanagari font if Marathi mode; fall back to English labels if absent */
  let mrFont = false;
  if (isMr) mrFont = await loadDevanagariFont(doc);

  // Labels follow lang; font quality degrades gracefully but labels always match
  const t        = isMr ? L.mr : L.en;
  const fontName = mrFont ? "NotoSansDevanagari" : "helvetica";
  const sf       = (bold = false) => doc.setFont(fontName, bold ? "bold" : "normal");

  /* ── Colour helpers ── */
  const fill = (...c: readonly [number, number, number]) => doc.setFillColor(c[0], c[1], c[2]);
  const tc   = (...c: readonly [number, number, number]) => doc.setTextColor(c[0], c[1], c[2]);
  const draw = (...c: readonly [number, number, number]) => doc.setDrawColor(c[0], c[1], c[2]);

  const hline = (yy: number) => {
    draw(...LIGHT_GREY);
    doc.setLineWidth(0.2);
    doc.line(M, yy, W - M, yy);
  };

  const sectionHeader = (title: string) => {
    fill(...OXBLOOD_MID);
    doc.rect(M, y, CW, 7, "F");
    tc(...GOLD);
    sf(true);
    doc.setFontSize(7.5);
    doc.text(title.toUpperCase(), M + 3, y + 5);
    y += 11;
  };

  const dataRow = (label: string, value: string, bold = false, shade = false) => {
    if (shade) {
      fill(245, 240, 235);
      doc.rect(M, y - 3, CW, 7, "F");
    }
    sf(bold);
    doc.setFontSize(9.5);
    tc(...INK);
    doc.text(label, M + 3, y + 1);
    doc.setFont("helvetica", bold ? "bold" : "normal"); // values always in Helvetica
    doc.text(value, W - M - 3, y + 1, { align: "right" });
    y += 7;
  };

  /* ════════════════════════════════════════════════════
     HEADER BAND
  ════════════════════════════════════════════════════ */
  fill(...OXBLOOD);
  doc.rect(0, 0, W, 42, "F");

  fill(...GOLD);
  doc.rect(0, 42, W, 1.2, "F");

  tc(...GOLD);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(24);
  doc.text("MUDRANKSEVA", M, 17);

  tc(...GOLD_MUTED);
  doc.setFont("helvetica", "normal");
  doc.setFontSize(7.5);
  doc.text("mudrankseva.in  \xB7  Maharashtra Property Services", M, 24);

  tc(255, 255, 255);
  sf(true);
  doc.setFontSize(13);
  doc.text(t.reportTitle, M, 35);

  const date = new Date().toLocaleDateString("en-IN", {
    day: "2-digit", month: "short", year: "numeric",
  });
  tc(...GOLD_MUTED);
  doc.setFont("helvetica", "normal");
  doc.setFontSize(8);
  doc.text(date, W - M, 35, { align: "right" });

  tc(180, 150, 150);
  doc.setFontSize(7.5);
  doc.text(t.reckoner, W - M, 24, { align: "right" });

  y = 50;

  /* ── Prepared for ── */
  tc(...GREY);
  sf(false);
  doc.setFontSize(9);
  doc.text(
    `${t.preparedFor}: ${name}${phone ? "  \xB7  +91 " + phone : ""}`,
    M, y,
  );
  y += 10;

  /* ════════════════════════════════════════════════════
     PROPERTY DETAILS
  ════════════════════════════════════════════════════ */
  sectionHeader(t.propDetails);

  const areaTypeLabel =
    areaType === "corporation" ? t.corp
    : areaType === "council"   ? t.council
    :                            t.rural;

  dataRow(t.propValue, fmt(result.propValue), true);
  if (district) dataRow(t.district, district, false, true);
  dataRow(t.areaType, areaTypeLabel, false, !district);
  dataRow(t.buyerType, result.isFemale ? t.female : t.male, false, true);
  if (surveyNo) dataRow(t.surveyNo, surveyNo);

  y += 3;

  /* ════════════════════════════════════════════════════
     STAMP DUTY BREAKDOWN
  ════════════════════════════════════════════════════ */
  sectionHeader(t.stampDuty);

  dataRow(`${t.baseStamp} (${pct(result.baseRate)})`, fmt(result.baseAmt));
  if (result.metroCessAmt !== null)
    dataRow(`${t.metroCess} (1%)`, fmt(result.metroCessAmt), false, true);
  if (result.lbtAmt !== null)
    dataRow(`${t.lbt} (1%)`, fmt(result.lbtAmt), false, result.metroCessAmt === null);

  hline(y + 1);
  y += 5;
  dataRow(`${t.totalStamp} (${pct(result.totalDutyRate)})`, fmt(result.totalDutyAmt), true);

  y += 4;
  sectionHeader(t.regCharges);
  dataRow(
    `${t.regFee} (1%${result.regFeeCapped ? `, ${t.regCapped}` : ""})`,
    fmt(result.regFeeAmt),
  );

  y += 5;

  /* ════════════════════════════════════════════════════
     GRAND TOTAL BAND
  ════════════════════════════════════════════════════ */
  fill(...OXBLOOD);
  doc.rect(M, y, CW, 16, "F");

  tc(...GOLD);
  sf(true);
  doc.setFontSize(10);
  doc.text(t.grandTotal.toUpperCase(), M + 5, y + 10);

  doc.setFont("helvetica", "bold");
  doc.setFontSize(17);
  doc.text(fmt(result.grandTotal), W - M - 5, y + 10.5, { align: "right" });

  y += 23;

  /* ════════════════════════════════════════════════════
     SAVINGS TIP — male buyers only
  ════════════════════════════════════════════════════ */
  if (!result.isFemale) {
    fill(255, 251, 232);
    draw(...GOLD);
    doc.setLineWidth(0.5);
    doc.roundedRect(M, y, CW, 17, 2, 2, "FD");

    tc(...OXBLOOD_MID);
    sf(true);
    doc.setFontSize(8.5);
    doc.text(t.savingsTip, M + 4, y + 7);

    tc(80, 50, 30);
    sf(false);
    doc.setFontSize(8);
    const tipLines = doc.splitTextToSize(t.savingsBody, CW - 8);
    doc.text(tipLines, M + 4, y + 13);
    y += 22;
  }

  y += 3;

  /* ════════════════════════════════════════════════════
     DISCLAIMER
  ════════════════════════════════════════════════════ */
  hline(y);
  y += 5;

  tc(...GREY);
  sf(false);
  doc.setFontSize(7);
  const disclaimerLines = doc.splitTextToSize(t.disclaimer, CW);
  doc.text(disclaimerLines, M, y);
  y += disclaimerLines.length * 3.8 + 5;

  /* ════════════════════════════════════════════════════
     UPSELL CARD
  ════════════════════════════════════════════════════ */
  fill(...CREAM);
  draw(...GOLD);
  doc.setLineWidth(0.4);
  doc.roundedRect(M, y, CW, 18, 2, 2, "FD");

  tc(...OXBLOOD_MID);
  sf(true);
  doc.setFontSize(9);
  doc.text(t.upsellTitle, M + 4, y + 7);

  tc(80, 50, 30);
  sf(false);
  doc.setFontSize(8);
  const upsellLines = doc.splitTextToSize(t.upsellBody, CW - 8);
  doc.text(upsellLines, M + 4, y + 13);

  /* ════════════════════════════════════════════════════
     FOOTER BAND
  ════════════════════════════════════════════════════ */
  fill(...OXBLOOD);
  doc.rect(0, 284, W, 13, "F");

  fill(...GOLD);
  doc.rect(0, 284, W, 0.8, "F");

  tc(...GOLD_MUTED);
  sf(false);
  doc.setFontSize(7.5);
  doc.text(t.footer, W / 2, 292, { align: "center" });

  /* ── Save ── */
  const safeName = name.replace(/[^\w\s]/g, "").replace(/\s+/g, "_").toLowerCase() || "client";
  doc.save(`mudrankseva_${t.fileTag}_${safeName}.pdf`);
}
