/* ── Currency formatter ──
   jsPDF Helvetica covers WinAnsiEncoding (Latin-1 only).
   U+20B9 RUPEE SIGN is outside that range, so we use "Rs." for reliable
   rendering. Devanagari labels are handled via Noto Sans Devanagari when
   the font is available (see loadDevanagariFont). */
const fmt = (n: number) =>
  "Rs. " + n.toLocaleString("en-IN", { maximumFractionDigits: 0 });

const pct = (r: number) => `${(r * 100).toFixed(0)}%`;

